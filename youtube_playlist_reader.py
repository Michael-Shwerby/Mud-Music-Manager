"""
Mud Music Manager - YouTube Playlist Reader

Reads a YouTube-native playlist's live video list directly via yt-dlp --
no Spotify involvement at all. This is the YouTube-native counterpart to
spotify_reader.py, built for Checklist item 6 (v0.15.0).

Per design Q3 (Checklist/design doc §5): a YouTube-native playlist's
tracks are downloaded in full, as-is -- the four-tier search in
youtube_matcher.py does NOT apply here, since the exact video to
download is already known (it's the playlist entry itself), unlike a
Spotify track where the matching video has to be found. This module
only reads playlist/video data; downloading is still handled by
downloader.py via acquisition_engine.acquire_youtube_native_track().

Per design Q2: a YouTube video has no Spotify-style catalog metadata.
The song title is always the video's own title, exactly as it appears
on YouTube. The rest of the metadata (Contributing Artist(s), Album,
Release Date) is scraped from the video's description ONLY when that
description is YouTube's own auto-generated one for an official music
upload (recognized by the literal "Auto-generated by YouTube." line
YouTube appends to those descriptions) -- see
_parse_auto_generated_description(). If a video's description isn't
recognizably auto-generated, no metadata is guessed or invented: the
video's channel name becomes the sole Artist, and Album/Year are left
blank, exactly as specified.

Performance/rate-limit note: unlike a flat playlist listing (fast, one
request), scraping a video's description requires a full per-video
info fetch. This module fetches those in parallel (mirroring
spotify_reader.py's parallel per-track detail fetch), but for a large
playlist this is meaningfully more yt-dlp traffic than a normal Sync
generates today -- worth keeping in mind alongside the project's
existing open investigation into 403 errors (see the Checklist), since
this is new request volume that investigation didn't originally
account for. Not yet live-tested against a real large playlist.
"""

import re
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass, field
from typing import Collection, List, Optional

import yt_dlp

import logger

# The exact line YouTube appends to a video's description when it was
# auto-generated for an official music upload. Its presence is the
# sole signal used to decide whether to trust the description for
# Contributing Artist(s)/Album/Release Date -- see design Q2. If this
# isn't present, nothing is scraped from the description at all.
AUTO_GENERATED_ANCHOR = "Auto-generated by YouTube."

_MIDDLE_DOT = "\u00b7"
_SOUND_RECORDING_COPYRIGHT = "\u2117"


@dataclass
class YouTubeTrack:
    """
    A single video's data from a YouTube-native playlist, plus its live
    position in the playlist it was read from. Deliberately exposes the
    same shared shape (.name, .primary_artist, .album_name, .year,
    .list_position, .cover_url) that metadata_tagger.tag_file() and
    lyrics_provider.get_lyrics() already expect from spotify_reader.Track,
    so both platforms' tracks can flow through the same tagging/lyrics
    code with no branching there.
    """
    video_id: str
    title: str
    artists: List[str] = field(default_factory=list)
    album_name: Optional[str] = None
    year: Optional[str] = None
    duration_ms: int = 0
    cover_url: Optional[str] = None
    channel_name: str = ""
    list_position: int = 0  # 1-indexed position in the playlist (live order)
    used_auto_generated_description: bool = False  # for logging/diagnostics only
    # YT Music (v0.16.51, Checklist item 42a; ytmusic_reader.py fills these,
    # a YouTube playlist leaves them as they are). An album track, as a
    # Spotify album Track: list_position is its track number, plus the
    # Disc # and the album's track count.
    disc_number: int = 0
    disc_total: int = 0
    track_total: int = 0
    # An album track YT Music lists as a video (not its audio-only upload):
    # Michael's choice is to download the audio-only (ATV) version instead
    # when there is one. audio_video_id is that version if the reader found
    # it already; otherwise the download looks for it.
    wants_audio_version: bool = False
    audio_video_id: Optional[str] = None

    @property
    def name(self) -> str:
        return self.title

    @property
    def primary_artist(self) -> str:
        return self.artists[0] if self.artists else self.channel_name

    @property
    def duration_seconds(self) -> float:
        return self.duration_ms / 1000 if self.duration_ms else 0.0


def _parse_auto_generated_description(description: Optional[str]):
    """
    Best-effort extraction of Contributing Artist(s), Album, and
    Release Date/Year from a video's description -- but ONLY if it's
    recognizably YouTube's own auto-generated description for an
    official music upload (see AUTO_GENERATED_ANCHOR and the module
    docstring). Returns None if the anchor phrase isn't present, or if
    nothing usable could be pulled out even though it is -- either way,
    the caller falls back to channel-name-only per design Q2, never
    guessing at a value this couldn't confirm.

    Typical shape of the description this is built for:
        Provided to YouTube by <Distributor>

        <Title> \u00b7 <Artist 1>, <Artist 2>

        <Album Name>

        \u2117 <Year> <Label>

        Released on: <YYYY-MM-DD>

        ...
        Auto-generated by YouTube.

    This layout isn't guaranteed to be perfectly consistent across
    every official upload, so each field is extracted independently
    and any single one that can't be found is simply left out, rather
    than the whole parse being abandoned.
    """
    if not description or AUTO_GENERATED_ANCHOR not in description:
        return None

    lines = [line.strip() for line in description.splitlines()]
    non_empty = [line for line in lines if line]

    artists = None
    album = None
    artist_line_index = None

    for i, line in enumerate(non_empty):
        if _MIDDLE_DOT in line:
            after_dot = line.split(_MIDDLE_DOT, 1)[1].strip()
            if after_dot:
                artists = [a.strip() for a in after_dot.split(",") if a.strip()]
                artist_line_index = i
            break

    if artist_line_index is not None and artist_line_index + 1 < len(non_empty):
        candidate = non_empty[artist_line_index + 1]
        looks_like_copyright_or_release = (
            candidate.startswith(_SOUND_RECORDING_COPYRIGHT)
            or candidate.lower().startswith("released on")
            or candidate.lower().startswith("provided to youtube")
        )
        if candidate and not looks_like_copyright_or_release:
            album = candidate

    year = None
    release_match = re.search(r"Released on:\s*(\d{4})", description, re.IGNORECASE)
    if release_match:
        year = release_match.group(1)
    else:
        copyright_match = re.search(rf"{_SOUND_RECORDING_COPYRIGHT}\s*(\d{{4}})", description)
        if copyright_match:
            year = copyright_match.group(1)

    if not artists and not album and not year:
        return None

    return {"artists": artists, "album": album, "year": year}


def _extract_playlist_flat(playlist_id_or_url: str) -> List[dict]:
    """One fast, shallow request for the playlist's video IDs/titles in
    live order -- no per-video details yet (those need a separate,
    full fetch per video, done by _fetch_full_video_info())."""
    url = (
        playlist_id_or_url
        if playlist_id_or_url.startswith("http")
        else f"https://www.youtube.com/playlist?list={playlist_id_or_url}"
    )
    ydl_opts = {
        "quiet": True,
        "no_warnings": True,
        "extract_flat": "in_playlist",
        "skip_download": True,
    }
    with yt_dlp.YoutubeDL(ydl_opts) as ydl:
        info = ydl.extract_info(url, download=False)
    return info.get("entries", []) or []


def _fetch_full_video_info(video_id: str) -> Optional[dict]:
    """Full per-video info (title, uploader, description, duration,
    thumbnail) -- needed for the description-scraping in design Q2.
    Falls back to None on failure; the caller falls back to the flat
    entry's shallower data rather than failing the whole playlist over
    one bad video."""
    url = f"https://www.youtube.com/watch?v={video_id}"
    ydl_opts = {"quiet": True, "no_warnings": True, "skip_download": True}
    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            return ydl.extract_info(url, download=False)
    except Exception as e:
        logger.log_error(f"Failed to fetch full video details for {video_id}: {e}")
        return None


def get_playlist_tracks(
    youtube_playlist_id: str,
    threads: int = 8,
    fetch_details: bool = True,
    skip_details_for: Optional[Collection[str]] = None,
) -> List[YouTubeTrack]:
    """
    Fetch the full, current video list for a YouTube-native playlist,
    in live playlist order, with per-video details (channel, and --
    where recognizable as auto-generated -- Contributing Artist(s),
    Album, Release Date) filled in via a per-video detail lookup (done
    in parallel for speed, matching spotify_reader.py's pattern).

    fetch_details: when False, skips the expensive per-video detail
    fetch entirely and builds each track from the fast flat playlist
    listing alone (title, channel name, position -- no description
    scraping, so no Album/Year, and Artist is just the channel name).
    Used by read-only Scan (library_sync.scan_playlist()), which only
    needs to know WHICH videos are live and in what order, not their
    full tag data -- a real Sync always uses the default (True).

    skip_details_for: video IDs (bare, no "yt:" prefix) that don't need
    the detail fetch even when fetch_details is True (Checklist item 26,
    v0.16.19) -- normally the ones already downloaded, which a Sync only
    renumbers or counts. Those are built from the flat listing alone,
    exactly as fetch_details=False builds every track. This also cuts
    the yt-dlp request volume noted in the module docstring.

    Raises RuntimeError with a clear, user-facing message if the
    playlist can't be read (not public/unlisted, wrong ID, empty, etc).
    """
    try:
        flat_entries = _extract_playlist_flat(youtube_playlist_id)
    except Exception as e:
        logger.log_error(f"Failed to read YouTube playlist {youtube_playlist_id}: {e}")
        raise RuntimeError(
            f"Could not read YouTube playlist '{youtube_playlist_id}'. Double check the "
            f"link/ID is correct and that the playlist is set to Public or Unlisted. ({e})"
        ) from e

    if not flat_entries:
        raise RuntimeError(
            f"YouTube playlist '{youtube_playlist_id}' returned no videos. It may be "
            f"empty, private, or the ID/link may be wrong."
        )

    basics = []
    for position, entry in enumerate(flat_entries, start=1):
        video_id = entry.get("id")
        if video_id:
            basics.append((position, video_id, entry))

    full_by_id = {}
    skip = set(skip_details_for or ())
    to_fetch = [video_id for _, video_id, _ in basics if video_id not in skip]
    if fetch_details and to_fetch:
        with ThreadPoolExecutor(max_workers=threads) as pool:
            future_to_id = {
                pool.submit(_fetch_full_video_info, video_id): video_id
                for video_id in to_fetch
            }
            for future in as_completed(future_to_id):
                video_id = future_to_id[future]
                full_by_id[video_id] = future.result()

    tracks: List[YouTubeTrack] = []
    for position, video_id, flat_entry in basics:
        full = full_by_id.get(video_id)

        title = (full or {}).get("title") or flat_entry.get("title") or video_id
        channel_name = (
            (full or {}).get("uploader")
            or (full or {}).get("channel")
            or flat_entry.get("uploader")
            or flat_entry.get("channel")
            or ""
        )
        description = (full or {}).get("description")
        duration = (full or {}).get("duration") if full else flat_entry.get("duration")
        thumbnail = (full or {}).get("thumbnail") if full else None

        parsed = _parse_auto_generated_description(description)
        if parsed:
            artists = parsed["artists"] or [channel_name]
            album_name = parsed["album"]
            year = parsed["year"]
            used_auto_generated = True
        else:
            artists = [channel_name]
            album_name = None
            year = None
            used_auto_generated = False

        tracks.append(YouTubeTrack(
            video_id=video_id,
            title=title,
            artists=artists,
            album_name=album_name,
            year=year,
            duration_ms=int(duration * 1000) if duration else 0,
            cover_url=thumbnail,
            channel_name=channel_name,
            list_position=position,
            used_auto_generated_description=used_auto_generated,
        ))

    tracks.sort(key=lambda t: t.list_position)
    return tracks
